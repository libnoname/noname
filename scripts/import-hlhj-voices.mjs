import { readdir, readFile, mkdir, copyFile, writeFile, unlink } from "node:fs/promises";
import { resolve, relative, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

// Import only reviewed folder-to-line mappings. Source takes remain intact.
// node scripts/import-hlhj-voices.mjs path/to/character-import.json
const root = fileURLToPath(new URL("../", import.meta.url));
const configPath = process.argv[2];
if (!configPath) throw new Error("请提供人物导入清单 JSON 路径");
const config = JSON.parse(await readFile(resolve(root, configPath), "utf8"));
if (!/^[a-z][a-z0-9_]*$/.test(config.character)) throw new Error("无效人物 ID");
const extension = resolve(root, "apps/core/extension/红楼幻境");
const inside = (base, path) => {
    const target = resolve(base, path), rel = relative(base, target);
    if (rel.startsWith("..") || /^[A-Za-z]:/.test(rel)) throw new Error("路径越界：" + path);
    return target;
};
const source = inside(extension, config.source);
const destination = inside(extension, `theme/voices/${config.character}`);
const manifestPath = inside(extension, `voice/import/${config.character}-selected.json`);
let previousImports = [];
try { previousImports = JSON.parse(await readFile(manifestPath, "utf8")).imports || []; }
catch (error) { if (error.code !== "ENOENT") throw error; }
const document = await readFile(inside(extension, config.document), "utf8");
const texts = new Map();
for (const row of document.split(/\r?\n/)) {
    const match = row.match(/^\|\s*([A-Z]+\d+)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|/);
    if (match) texts.set(match[1], /^(JZ|ZH|QS|EN|D|TS)\d+$/.test(match[1]) ? match[2] : match[3]);
}
const clips = {}, imports = [];
const compare = (a, b) => a.localeCompare(b, "zh-CN", { numeric: true });
// Preflight every mapping before writing any asset. Missing lines stay absent,
// never shift later recordings onto the preceding text.
for (const [folder, id] of Object.entries(config.folders)) {
    if (!/^[A-Z]+\d{2}$/.test(id) || !texts.has(id) || clips[id]) throw new Error("重复或未知台词编号：" + id);
    const path = inside(source, folder);
    const entries = await readdir(path, { withFileTypes: true });
    if (entries.some(entry => entry.isSymbolicLink())) throw new Error("不支持配音目录中的符号链接：" + folder);
    const takes = entries.filter(entry => entry.isFile() && /\.mp3$/i.test(entry.name)).map(entry => entry.name).sort(compare);
    if (!takes.length) throw new Error("配音文件夹为空：" + folder);
    clips[id] = { variants: [], text: texts.get(id) };
    for (let index = 0; index < takes.length; index++) {
        const take = takes[index], variant = String(index + 1).padStart(2, "0");
        const file = `${config.character}_${id.toLowerCase()}_${variant}.mp3`;
        const bytes = await readFile(join(path, take));
        clips[id].variants.push(file);
        imports.push({ id, variant, source: folder + "/" + take, file, sha256: createHash("sha256").update(bytes).digest("hex") });
    }
}
await mkdir(destination, { recursive: true });
for (const entry of imports) await copyFile(inside(source, entry.source), join(destination, entry.file));
const catalogDir = inside(extension, "voice/catalogs");
await mkdir(catalogDir, { recursive: true });
await writeFile(join(catalogDir, config.character + ".js"), "// Generated by scripts/import-hlhj-voices.mjs. All takes; choose a variant at playback.\nexport const clips = " + JSON.stringify(clips, null, 4) + ";\n");
// The built-in character adapter uses the existing static image resource root.
const mirror = inside(root, `apps/core/image/hlhj/theme/voices/${config.character}`);
await mkdir(mirror, { recursive: true });
for (const { file } of imports) await copyFile(join(destination, file), join(mirror, file));
// Remove only obsolete files generated by the previous import, and only if
// their bytes are unchanged. Never remove originals or unrelated media.
const files = new Set(imports.map(entry => entry.file));
for (const entry of previousImports) {
    if (files.has(entry.file)) continue;
    for (const base of [destination, mirror]) {
        const path = inside(base, entry.file);
        try {
            const hash = createHash("sha256").update(await readFile(path)).digest("hex");
            if (hash === entry.sha256) await unlink(path);
        } catch (error) { if (error.code !== "ENOENT") throw error; }
    }
}
await mkdir(inside(extension, "voice/import"), { recursive: true });
await writeFile(manifestPath, JSON.stringify({ character: config.character, source: config.source, mode: "random-variants", missing: config.missing || [], pendingGroups: config.pendingGroups || [], imports }, null, 2) + "\n");
console.log(`已规范命名 ${Object.keys(clips).length} 句台词的 ${imports.length} 个演绎版本，并同步开发客户端资源；原文件保留。`);
