import { cp, readdir, writeFile, unlink } from "node:fs/promises";
import { themes } from "../apps/core/extension/红楼幻境/theme/catalog.js";
import { basename } from "node:path";

// Browser clients cannot enumerate static directories. Generate the checked-in
// catalog after adding/removing MP3/M4A files, then refresh the dev-client mirror.
const source = new URL("../apps/core/extension/红楼幻境/theme/", import.meta.url);
const mirror = new URL("../apps/core/image/hlhj/theme/", import.meta.url);
for (const theme of Object.values(themes)) {
    const entries = await readdir(new URL(theme.album + "/", source), { withFileTypes: true });
    const tracks = entries.filter(entry => entry.isFile() && /\.(mp3|m4a)$/i.test(entry.name))
        .map(entry => entry.name).sort((a, b) => a.localeCompare(b, "zh-CN", { numeric: true }));
    if (!tracks.length) throw new Error(`歌单目录为空：${theme.album}`);
    theme.tracks = tracks.map(name => `${theme.album}/${name}`);
}
await writeFile(new URL("catalog.js", source), "// Generated by node scripts/sync-hlhj-theme.mjs; paths are relative to theme/.\nexport const themes = " + JSON.stringify(themes, null, 4) + ";\n");
await cp(source, mirror, { recursive: true, filter: path => !basename(path).endsWith("_配音") });
// Remove only obsolete mirrored audio files; the source folder is never deleted.
for (const theme of Object.values(themes)) {
    const folder = new URL(theme.album + "/", mirror);
    for (const entry of await readdir(folder, { withFileTypes: true })) {
        if (entry.isFile() && /\.(mp3|m4a)$/i.test(entry.name) && !theme.tracks.includes(`${theme.album}/${entry.name}`)) {
            await unlink(new URL(entry.name, folder));
        }
    }
}
console.log(`已同步 ${Object.keys(themes).length} 套背景与 ${Object.values(themes).reduce((count, theme) => count + theme.tracks.length, 0)} 首曲目。`);
